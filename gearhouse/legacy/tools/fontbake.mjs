// node tools/fontbake.mjs <Galmuri7.bdf> -> game/font_ko.mjs
// Bakes ONLY the glyphs the UI needs (Korean table + printable ASCII) from the Galmuri 7px bitmap font (SIL OFL 1.1,
// see docs/licenses/Galmuri-OFL.md) into a compact bitmap table, so the game draws real pixel glyphs (no font smoothing).
import { readFileSync, writeFileSync } from 'node:fs';
import { KO } from '../game/i18n.mjs';
const bdf = readFileSync(process.argv[2], 'utf8'), want = new Set();
for (let c = 32; c < 127; c++) want.add(c); for (const v of Object.values(KO)) for (const ch of v) want.add(ch.codePointAt(0));
for (const ch of '~·…→←↑↓%$₩') want.add(ch.codePointAt(0));
const G = {}; let asc = 9;
for (const blk of bdf.split('STARTCHAR').slice(1)) {
  const enc = +(/ENCODING (\d+)/.exec(blk) || [])[1]; if (!want.has(enc)) continue;
  const dw = +/DWIDTH (\d+)/.exec(blk)[1], [bw, bh, xo, yo] = /BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)/.exec(blk).slice(1).map(Number);
  const rows = blk.split('BITMAP')[1].split('ENDCHAR')[0].trim().split(/\s+/).filter(Boolean).map(h => parseInt(h, 16) >> (h.length * 4 - Math.max(bw, 1)));
  G[enc] = [dw, bw, bh, xo, yo, ...rows]; }
const m = /FONT_ASCENT (\d+)/.exec(bdf); if (m) asc = +m[1];
const missing = [...want].filter(c => !G[c] && c > 32).map(c => String.fromCodePoint(c));
writeFileSync(new URL('../game/font_ko.mjs', import.meta.url), `// Galmuri7 subset (SIL OFL 1.1, (c) quiple) - generated by tools/fontbake.mjs, do not edit\nexport const FONT = { ascent: ${asc}, g: ${JSON.stringify(G)} };\n`);
console.log('glyphs', Object.keys(G).length, 'missing', missing.join(''));
