// node tools/fontbakeFull.mjs <Galmuri7.bdf> -> game/font_ko_full.mjs
// Every Hangul syllable (11,172) + compatibility jamo (shown while a name is being composed) from Galmuri7 (SIL OFL 1.1,
// see docs/licenses/Galmuri-OFL.md), packed as base64 records so player-typed names can use any Korean word.
// Loaded on demand the first time a name field is used. Record: dw, bw, bh, xo+16, yo+16, then bh rows (1 byte if bw <= 8 else 2).
import { readFileSync, writeFileSync } from 'node:fs';
const bdf = readFileSync(process.argv[2], 'utf8'), ranges = [[0xAC00, 11172], [0x3131, 94], [0x00C0, 64]], want = new Set();
for (const [a, n] of ranges) for (let c = a; c < a + n; c++) want.add(c);
const G = {};
for (const blk of bdf.split('STARTCHAR').slice(1)) {
  const enc = +(/ENCODING (\d+)/.exec(blk) || [])[1]; if (!want.has(enc)) continue;
  const dw = +/DWIDTH (\d+)/.exec(blk)[1], [bw, bh, xo, yo] = /BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+)/.exec(blk).slice(1).map(Number);
  const rows = blk.split('BITMAP')[1].split('ENDCHAR')[0].trim().split(/\s+/).filter(Boolean).map(h => parseInt(h, 16) >> (h.length * 4 - Math.max(bw, 1)));
  G[enc] = [dw, bw, bh, xo, yo, ...rows]; }
const bytes = [];
for (const [a, n] of ranges) for (let c = a; c < a + n; c++) { const g = G[c] || [0, 0, 0, 0, 0]; const [dw, bw, bh, xo, yo, ...rows] = g; bytes.push(dw, bw, bh, xo + 16, yo + 16);
  for (let j = 0; j < bh; j++) { const r = rows[j] || 0; if (bw > 8) bytes.push(r >> 8, r & 255); else bytes.push(r); } }
const b64 = Buffer.from(bytes).toString('base64');
writeFileSync(new URL('../game/font_ko_full.mjs', import.meta.url), `// Galmuri7 Hangul set (SIL OFL 1.1, (c) quiple) - generated by tools/fontbakeFull.mjs, do not edit
const R = ${JSON.stringify(ranges)}, D = '${b64}';
export function decode() { const b = atob(D), g = {}; let i = 0; const u = () => b.charCodeAt(i++);
  for (const [a, n] of R) for (let c = a; c < a + n; c++) { const dw = u(), bw = u(), bh = u(), xo = u() - 16, yo = u() - 16, rows = []; for (let j = 0; j < bh; j++) rows.push(bw > 8 ? (u() << 8) | u() : u()); if (dw) g[c] = [dw, bw, bh, xo, yo, ...rows]; }
  return g; }
`);
console.log('glyphs', Object.keys(G).length, 'bytes', bytes.length, 'file', Math.round(b64.length / 1024) + 'KB');
