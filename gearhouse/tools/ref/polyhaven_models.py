# Props for the circuit (review 125): Poly Haven CC0 models fetched as glTF at 1K, each into assets/models/<id>/ with its
# .gltf, .bin and textures (diffuse, normal GL, arm: ao rough metal). models.json lists them with their sources.
#   python3 tools/ref/polyhaven_models.py
import json, os, urllib.request
IDS = ['barrel_03', 'Barrel_01', 'old_tyre', 'old_military_crate', 'painted_wooden_bench', 'WoodenTable_01', 'folding_wooden_stool', 'metal_jerrycan', 'oil_tin']
H = {'User-Agent': 'gearhouse-texture-fetch/1.0'}
get = lambda u: urllib.request.urlopen(urllib.request.Request(u, headers=H), timeout=120).read()
meta = []
for pid in IDS:
    files = json.loads(get(f'https://api.polyhaven.com/files/{pid}')); info = json.loads(get(f'https://api.polyhaven.com/info/{pid}'))
    g = files['gltf']['1k']['gltf']; d = f'assets/models/{pid}'; os.makedirs(d + '/textures', exist_ok=True)
    open(f'{d}/{pid}.gltf', 'wb').write(get(g['url']))
    for rel, f in g.get('include', {}).items():
        if 'nor_dx' in rel or 'rough' in rel.split('/')[-1] and 'arm' not in rel: pass
        p = f'{d}/{rel}'; os.makedirs(os.path.dirname(p), exist_ok=True); open(p, 'wb').write(get(f['url']))
    meta.append({'id': pid, 'source': f'https://polyhaven.com/a/{pid}', 'authors': list(info['authors'].keys()), 'license': 'CC0', 'polycount': info.get('polycount')})
    print(pid, sorted(os.listdir(d + '/textures')))
json.dump({'about': 'Poly Haven CC0 props (review 125), glTF 1K', 'models': meta}, open('assets/models/models.json', 'w'), indent=1)
# small things: their pictures at 512 (a crate or a drum is never more than a few hundred pixels on screen)
from PIL import Image
import glob
for f in glob.glob('assets/models/*/textures/*.jpg'):
    im = Image.open(f); im.convert('RGB').resize((512, 512), Image.LANCZOS).save(f, quality=85)
# the module the page imports: each model's glTF (as data), its buffer and pictures (as files beside the page)
lines = ['// Generated by tools/ref/polyhaven_models.py (review 125): the circuit props, Poly Haven CC0 glTF.']
ent = []
for k, m in enumerate(meta):
    pid = m['id']; g = json.load(open(f'assets/models/{pid}/{pid}.gltf')); uris = [b['uri'] for b in g.get('buffers', [])] + [i['uri'] for i in g.get('images', [])]
    lines.append(f"import g{k} from '../../assets/models/{pid}/{pid}.gltf';")
    files = []
    for j, u in enumerate(uris): lines.append(f"import f{k}_{j} from '../../assets/models/{pid}/{u}';"); files.append(f"'{u}': f{k}_{j}")
    ent.append(f"  {pid}: {{ gltf: g{k} as unknown as Gltf, files: {{ {', '.join(files)} }} }},")
lines.insert(1, "import type { Gltf } from './gltf';")
lines.append('export const PROP_MODELS: Record<string, { gltf: Gltf; files: Record<string, string> }> = {'); lines += ent; lines.append('};')
open('render/live/propmodels.ts', 'w').write('\n'.join(lines) + '\n'); print('wrote render/live/propmodels.ts')
